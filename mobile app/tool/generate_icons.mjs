#!/usr/bin/env node
/**
 * Generates every platform app icon from the vector sources in
 * `mobile app/assets/icons/`.
 *
 *   node "mobile app/tool/generate_icons.mjs"
 *
 * Sources (edit these, then re-run):
 *   app_icon.svg            full-bleed 1024 art (Android adaptive background,
 *                           Linux 512, Play Store, docs)
 *   app_icon_compact.svg    same mark at 130% for small legacy/desktop sizes
 *   app_icon_foreground.svg transparent 108dp Android adaptive foreground
 *   app_icon_monochrome.svg Android 13 themed-icon silhouette
 *
 * Outputs:
 *   Android  mipmap-<density> legacy + round launchers, adaptive foreground and
 *            monochrome layers, drawable background, anydpi-v26/v33 adaptive XML
 *   Windows  windows/runner/resources/app_icon.ico (16-256, multi-size)
 *   Linux    linux/icons/hicolor/<size>/apps/water_project.png + scalable SVG
 *            and linux/water_project.desktop
 *
 * Setup (one time):  cd "mobile app/tool" && npm install
 * Run:               node "mobile app/tool/generate_icons.mjs"
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');
const APP = path.join(ROOT, 'mobile app');
const SRC = path.join(APP, 'assets', 'icons');
const ANDROID_RES = path.join(APP, 'android', 'app', 'src', 'main', 'res');
const WIN_RES = path.join(APP, 'windows', 'runner', 'resources');
const LINUX = path.join(APP, 'linux');

const read = (name) => fs.readFileSync(path.join(SRC, name), 'utf8');

/** Rasterise an SVG string at exactly `size` px. */
function render(svg, size, background = 'rgba(0,0,0,0)') {
  const resvg = new Resvg(svg, {
    fitTo: { mode: 'width', value: size },
    background,
    shapeRendering: 2,
    imageRendering: 0,
  });
  const img = resvg.render();
  return { png: img.asPng(), pixels: img.pixels, width: img.width, height: img.height };
}

function writePng(file, svg, size, background) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const { png } = render(svg, size, background);
  fs.writeFileSync(file, png);
  return png.length;
}

/**
 * Below 32 px the amber highlight collapses into a smudge, so the tiny sizes are
 * drawn from a simplified variant: same droplet, no accent stroke.
 */
const stripAmber = (svg) => svg.replace(/\n\s*<line[^>]*stroke="#FDA107"[^>]*\/>/, '');

/** Wrap the full-bleed art in a circle mask (Android round icon, Linux round). */
function circleMasked(svgSource) {
  return svgSource
    .replace('<svg ', '<svg ')
    .replace(
      /(<rect width="1024" height="1024"[^/]*\/>)/,
      '<clipPath id="round"><circle cx="512" cy="512" r="512"/></clipPath>' +
        '<g clip-path="url(#round)">$1',
    )
    .replace('</svg>', '</g></svg>');
}

// ---------------------------------------------------------------- Android ---
const ANDROID_DENSITIES = [
  ['mdpi', 48, 108],
  ['hdpi', 72, 162],
  ['xhdpi', 96, 216],
  ['xxhdpi', 144, 324],
  ['xxxhdpi', 192, 432],
];

function buildAndroid() {
  const full = read('app_icon.svg');
  const compact = read('app_icon_compact.svg');
  const round = circleMasked(compact);
  const foreground = read('app_icon_foreground.svg');
  const monochrome = read('app_icon_monochrome.svg');

  for (const [density, legacy, adaptive] of ANDROID_DENSITIES) {
    const dir = path.join(ANDROID_RES, `mipmap-${density}`);
    writePng(path.join(dir, 'ic_launcher.png'), compact, legacy);
    writePng(path.join(dir, 'ic_launcher_round.png'), round, legacy);
    writePng(path.join(dir, 'ic_launcher_foreground.png'), foreground, adaptive);
    writePng(path.join(dir, 'ic_launcher_monochrome.png'), monochrome, adaptive);
  }

  // Adaptive background: vector drawable with the brand gradient (API 26+).
  const backgroundXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by mobile app/tool/generate_icons.mjs - do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="0"
                android:startY="0"
                android:endX="108"
                android:endY="108">
                <item android:offset="0" android:color="#FF042F51" />
                <item android:offset="0.52" android:color="#FF025B7A" />
                <item android:offset="1" android:color="#FF0285A2" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
`;
  fs.mkdirSync(path.join(ANDROID_RES, 'drawable'), { recursive: true });
  fs.writeFileSync(path.join(ANDROID_RES, 'drawable', 'ic_launcher_background.xml'), backgroundXml);

  const adaptive = (withMonochrome) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by mobile app/tool/generate_icons.mjs - do not edit by hand. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />${withMonochrome ? '\n    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />' : ''}
</adaptive-icon>
`;
  const v26 = path.join(ANDROID_RES, 'mipmap-anydpi-v26');
  const v33 = path.join(ANDROID_RES, 'mipmap-anydpi-v33');
  fs.mkdirSync(v26, { recursive: true });
  fs.mkdirSync(v33, { recursive: true });
  fs.writeFileSync(path.join(v26, 'ic_launcher.xml'), adaptive(false));
  fs.writeFileSync(path.join(v26, 'ic_launcher_round.xml'), adaptive(false));
  fs.writeFileSync(path.join(v33, 'ic_launcher.xml'), adaptive(true));
  fs.writeFileSync(path.join(v33, 'ic_launcher_round.xml'), adaptive(true));

  // Play Store / documentation master.
  writePng(path.join(SRC, 'app_icon_1024.png'), full, 1024);
  writePng(path.join(SRC, 'app_icon_compact_1024.png'), compact, 1024);
  writePng(path.join(SRC, 'ic_launcher-playstore-512.png'), full, 512);
  console.log('android: mipmaps, adaptive XML, Play Store 512');
}

// ---------------------------------------------------------------- Windows ---
/**
 * Multi-resolution .ico. Entries below 256 px are written as 32-bit BGRA DIBs
 * (the format every Windows shell version understands); 256 px is embedded PNG.
 */
function buildIco(svg) {
  const tiny = stripAmber(svg);
  const sizes = [16, 20, 24, 32, 40, 48, 64, 128, 256];
  const entries = sizes.map((size) => {
    const { png, pixels } = render(size < 32 ? tiny : svg, size);
    return { size, png, pixels, usePng: size >= 256 };
  });

  const dib = (w, h, rgba) => {
    const header = Buffer.alloc(40);
    const maskRow = Math.ceil(w / 32) * 4; // 1bpp AND mask, 4-byte aligned
    header.writeUInt32LE(40, 0); // biSize
    header.writeInt32LE(w, 4); // biWidth
    header.writeInt32LE(h * 2, 8); // biHeight (XOR + AND)
    header.writeUInt16LE(1, 12); // biPlanes
    header.writeUInt16LE(32, 14); // biBitCount
    header.writeUInt32LE(0, 16); // BI_RGB
    header.writeUInt32LE(w * h * 4 + maskRow * h, 20); // biSizeImage
    const xor = Buffer.alloc(w * h * 4);
    for (let y = 0; y < h; y += 1) {
      const srcRow = (h - 1 - y) * w * 4;
      const dstRow = y * w * 4;
      for (let x = 0; x < w; x += 1) {
        const s = srcRow + x * 4;
        const d = dstRow + x * 4;
        xor[d] = rgba[s + 2]; // B
        xor[d + 1] = rgba[s + 1]; // G
        xor[d + 2] = rgba[s]; // R
        xor[d + 3] = rgba[s + 3]; // A
      }
    }
    return Buffer.concat([header, xor, Buffer.alloc(maskRow * h)]);
  };

  const blobs = entries.map((e) => (e.usePng ? e.png : dib(e.size, e.size, e.pixels)));
  const dir = Buffer.alloc(6);
  dir.writeUInt16LE(0, 0);
  dir.writeUInt16LE(1, 2); // type: icon
  dir.writeUInt16LE(entries.length, 4);
  let offset = 6 + entries.length * 16;
  const dirEntries = entries.map((e, i) => {
    const b = Buffer.alloc(16);
    b.writeUInt8(e.size >= 256 ? 0 : e.size, 0);
    b.writeUInt8(e.size >= 256 ? 0 : e.size, 1);
    b.writeUInt8(0, 2);
    b.writeUInt8(0, 3);
    b.writeUInt16LE(1, 4); // planes
    b.writeUInt16LE(32, 6); // bit depth
    b.writeUInt32LE(blobs[i].length, 8);
    b.writeUInt32LE(offset, 12);
    offset += blobs[i].length;
    return b;
  });
  return Buffer.concat([dir, ...dirEntries, ...blobs]);
}

function buildWindows() {
  const compact = read('app_icon_compact.svg');
  fs.writeFileSync(path.join(WIN_RES, 'app_icon.ico'), buildIco(compact));
  console.log('windows: app_icon.ico (16,20,24,32,40,48,64,128,256)');
}

// ------------------------------------------------------------------ Linux ---
const LINUX_SIZES = [16, 22, 24, 32, 48, 64, 128, 256, 512];

function buildLinux() {
  const compact = read('app_icon_compact.svg');
  const tiny = stripAmber(compact);
  for (const size of LINUX_SIZES) {
    writePng(
      path.join(LINUX, 'icons', 'hicolor', `${size}x${size}`, 'apps', 'water_project.png'),
      size < 32 ? tiny : compact,
      size,
    );
  }
  fs.mkdirSync(path.join(LINUX, 'icons', 'hicolor', 'scalable', 'apps'), { recursive: true });
  fs.copyFileSync(
    path.join(SRC, 'app_icon_compact.svg'),
    path.join(LINUX, 'icons', 'hicolor', 'scalable', 'apps', 'water_project.svg'),
  );

  const desktop = `[Desktop Entry]
Type=Application
Name=Water Project
Name[ar]=مشروع المياه
Comment=Water project administration and field operations
Comment[ar]=إدارة مشروع المياه والعمل الميداني
Exec=water_project
Icon=water_project
Terminal=false
Categories=Office;Finance;
StartupWMClass=water_project
`;
  fs.writeFileSync(path.join(LINUX, 'water_project.desktop'), desktop);
  console.log('linux: hicolor icons 16-512 + scalable + .desktop');
}

buildAndroid();
buildWindows();
buildLinux();
buildPreview();
console.log('done');

// ---------------------------------------------------------------- Preview ---
/** Documentation board (assets/icons/preview.png) composed from the real outputs. */
function buildPreview() {
  const fontFiles = ['Tajawal-Regular.ttf', 'Tajawal-Bold.ttf'].map((f) =>
    path.join(APP, 'assets', 'fonts', f),
  );
  const dataUri = (file) => `data:image/png;base64,${fs.readFileSync(file).toString('base64')}`;
  const dataUriSvg = (svg) => `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;

  const W = 1280;
  const H = 940;
  const out = [];
  const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const text = (x, y, s, size, fill, weight = 400, anchor = 'start') =>
    out.push(
      `<text x="${x}" y="${y}" font-family="Tajawal" font-size="${size}" font-weight="${weight}" fill="${fill}" text-anchor="${anchor}">${esc(s)}</text>`,
    );
  const card = (x, y, w, h, title, sub) => {
    out.push(`<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="18" fill="#FFFFFF" stroke="#CBD5E1"/>`);
    text(x + 24, y + 40, title, 22, '#0F172A', 700);
    text(x + 24, y + 66, sub, 14, '#64748B');
  };
  const img = (href, x, y, size) =>
    out.push(`<image href="${href}" x="${x}" y="${y}" width="${size}" height="${size}"/>`);

  text(48, 60, 'Water Project — app icons', 34, '#0F172A', 700);
  text(48, 92, 'Android · Windows · Linux  |  generated from mobile app/assets/icons/*.svg by tool/generate_icons.mjs', 16, '#64748B');

  // --- Android ---
  card(48, 124, 584, 372, 'Android', 'adaptive launcher (API 26+) · round · legacy · themed');
  out.push('<defs><clipPath id="av"><circle cx="146" cy="260" r="60"/></clipPath></defs>');
  out.push(`<image href="${dataUri(path.join(SRC, 'app_icon_1024.png'))}" x="86" y="200" width="120" height="120" clip-path="url(#av)"/>`);
  out.push(`<image href="${dataUri(path.join(ANDROID_RES, 'mipmap-xxxhdpi', 'ic_launcher_foreground.png'))}" x="86" y="200" width="120" height="120" clip-path="url(#av)"/>`);
  img(dataUri(path.join(ANDROID_RES, 'mipmap-xxxhdpi', 'ic_launcher_round.png')), 236, 200, 120);
  img(dataUri(path.join(ANDROID_RES, 'mipmap-xxxhdpi', 'ic_launcher.png')), 386, 200, 120);
  const tintedMono = read('app_icon_monochrome.svg').replace('#FFFFFF', '#EAB308');
  img(dataUriSvg(tintedMono), 486, 210, 100);
  ['adaptive', 'round', 'legacy', 'themed'].forEach((label, i) =>
    text([146, 296, 446, 536][i], 340, label, 14, '#64748B', 400, 'middle'),
  );
  text(86, 386, 'mipmaps 48 / 72 / 96 / 144 / 192 px legacy, 108 to 432 px adaptive layers', 13, '#64748B');
  text(86, 408, 'themed icons: monochrome layer tinted by the system palette', 13, '#64748B');
  text(86, 442, 'manifest: android:icon=@mipmap/ic_launcher', 13, '#64748B');
  text(86, 464, 'android:roundIcon=@mipmap/ic_launcher_round', 13, '#64748B');

  // --- Windows ---
  card(648, 124, 584, 372, 'Windows', 'app_icon.ico — one file, nine embedded sizes');
  let x = 692;
  const compactSvg = dataUriSvg(read('app_icon_compact.svg'));
  for (const size of [128, 64, 48, 32, 20, 16]) {
    img(compactSvg, x, 324 - size, size);
    text(x + size / 2, 352, String(size), 14, '#64748B', 400, 'middle');
    x += size + 30;
  }
  text(692, 430, '16, 20, 24, 32, 40, 48, 64, 128, 256 px (256 stored as PNG)', 13, '#64748B');
  text(692, 452, 'used by the window, taskbar, Start menu and Explorer', 13, '#64748B');

  // --- Linux ---
  card(48, 516, 1184, 376, 'Linux', 'hicolor icon theme + .desktop entry  ->  /usr/share/icons/hicolor');
  x = 86;
  for (const [size, show] of [[512, 170], [256, 170], [128, 170], [64, 64], [48, 48], [32, 32], [24, 24], [22, 22], [16, 16]]) {
    const file = path.join(LINUX, 'icons', 'hicolor', `${size}x${size}`, 'apps', 'water_project.png');
    img(dataUri(file), x, 600 + (170 - show), show);
    text(x + show / 2, 600 + 170 + 22, `${size} px`, 14, '#64748B', 400, 'middle');
    x += show + 36;
  }
  text(86, 826, 'install: cp icons/hicolor/<size>/apps/water_project.png -> /usr/share/icons/hicolor/<size>/apps/', 13, '#64748B');
  text(86, 848, 'water_project.desktop -> /usr/share/applications/   |   scalable SVG included for HiDPI/Wayland', 13, '#64748B');

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
  <rect width="${W}" height="${H}" fill="#F1F5F9"/>
${out.join('\n')}
</svg>
`;
  const preview = new Resvg(svg, {
    fitTo: { mode: 'width', value: W },
    font: { fontFiles, loadSystemFonts: false, defaultFontFamily: 'Tajawal' },
    shapeRendering: 2,
    imageRendering: 0,
  });
  fs.writeFileSync(path.join(SRC, 'preview.png'), preview.render().asPng());
  console.log('preview: assets/icons/preview.png');
}
